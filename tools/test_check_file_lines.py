import unittest

from check_file_lines import LINE_LIMIT, check, measure, read_baseline, render_baseline


def lines(count: int) -> str:
    return "x\n" * count


class FileLinesTests(unittest.TestCase):
    def test_a_new_file_over_the_limit_fails_and_one_at_it_passes(self):
        measured = measure(
            {"app/a.rs": lines(LINE_LIMIT), "app/b.rs": lines(LINE_LIMIT + 3)}
        )
        failures, lowered = check(measured, {})
        self.assertEqual(
            [(f.path, f.lines) for f in failures], [("app/b.rs", LINE_LIMIT + 3)]
        )
        self.assertIn("by 3", failures[0].message)
        self.assertEqual(lowered, {})

    def test_tests_generated_files_and_inline_test_modules_are_not_counted(self):
        rust = lines(10) + "#[cfg(test)]\nmod tests {\n" + lines(900) + "}\n"
        measured = measure(
            {
                "app/core.rs": rust,
                "app/core/tests.rs": lines(900),
                "app/storage_tests/x.rs": lines(900),
                "cli/tests/init.rs": lines(900),
                "tools/test_x.py": lines(900),
                "dashboard/src/a.test.ts": lines(900),
                "dashboard/src/contract.ts": "/**\n * This file was auto-generated by openapi-typescript.\n */\n"
                + lines(900),
                "crates/x/src/generated/q.rs": lines(900),
                "README.md": lines(900),
            }
        )
        self.assertEqual(measured, {"app/core.rs": 10})

    def test_a_recorded_file_may_not_grow_and_must_be_lowered_as_it_shrinks(self):
        baseline = {"app/big.rs": 900}
        failures, _ = check({"app/big.rs": 901}, baseline)
        self.assertIn("grew past its recorded 900", failures[0].message)
        failures, _ = check({"app/big.rs": 900}, baseline)
        self.assertEqual(failures, [])
        failures, lowered = check({"app/big.rs": 850}, baseline)
        self.assertIn("--update", failures[0].message)
        self.assertEqual(lowered, {"app/big.rs": 850})
        # Once under the limit, or gone, the entry is dropped.
        for measured in ({"app/big.rs": 400}, {}):
            failures, lowered = check(measured, baseline)
            self.assertEqual(len(failures), 1)
            self.assertEqual(lowered, {})

    def test_the_baseline_round_trips_and_rejects_malformed_lines(self):
        entries = {"b.rs": 700, "a.rs": 600}
        self.assertEqual(read_baseline(render_baseline(entries)), entries)
        with self.assertRaises(ValueError):
            read_baseline("many app/a.rs\n")


if __name__ == "__main__":
    unittest.main()
